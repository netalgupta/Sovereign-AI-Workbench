"""Huge, realistic spreadsheets. Zero model calls.

An LLM authoring six years of daily instrument readings one cell at a
time would be three orders of magnitude slower than this AND less
realistic -- a real historian export is generated by an instrument, not
narrated. numpy with a seeded RNG produces trend + seasonal + noise +
occasional excursion, which is the actual shape of six years of plant
data, and does it for thousands of rows in under a second.
"""

from __future__ import annotations

from datetime import date, timedelta
from pathlib import Path

import numpy as np
from openpyxl import Workbook
from openpyxl.styles import Font, PatternFill
from openpyxl.utils import get_column_letter

from . import vocab

_HEADER_FILL = PatternFill(start_color="1F2937", end_color="1F2937", fill_type="solid")
_HEADER_FONT = Font(color="FFFFFF", bold=True)
_EXCEED_FILL = PatternFill(start_color="FDE2E1", end_color="FDE2E1", fill_type="solid")


def _style_header(ws, row: int, ncols: int) -> None:
    for c in range(1, ncols + 1):
        cell = ws.cell(row=row, column=c)
        cell.fill = _HEADER_FILL
        cell.font = _HEADER_FONT
    ws.freeze_panes = ws.cell(row=row + 1, column=1)


def _autosize(ws, ncols: int, sample_rows: int = 200) -> None:
    for c in range(1, ncols + 1):
        letter = get_column_letter(c)
        width = max(
            (len(str(ws.cell(row=r, column=c).value or "")) for r in range(1, min(sample_rows, ws.max_row) + 1)),
            default=10,
        )
        ws.column_dimensions[letter].width = min(max(width + 2, 10), 40)


def generate_process_readings_log(
    output_path: Path,
    start: date = date(2020, 1, 1),
    end: date = date(2026, 9, 14),
) -> dict:
    """Daily instrument readings, one sheet per unit, for the whole span.

    THE SHAPE, deliberately not flat noise. Each parameter gets a slow
    multi-year drift (catalyst aging, seasonal ambient effects) plus
    daily noise plus a small number of genuine excursions above spec --
    a flat random walk would make every "was there ever a spec
    exceedance" question either trivially yes-everywhere or
    trivially no-anywhere, and neither exercises retrieval honestly.

    Returns stats: {sheet_name: {rows, exceedances}}.
    """
    wb = Workbook()
    wb.remove(wb.active)
    stats: dict = {}

    n_days = (end - start).days + 1
    dates = [start + timedelta(days=i) for i in range(n_days)]

    for unit in vocab.UNITS:
        rng = np.random.default_rng(abs(hash(f"readings::{unit}")) % (2**32))
        ws = wb.create_sheet(title=unit[:31])  # Excel sheet name limit

        params = vocab.SPEC_PARAMS
        header = ["Date", "Day of Week"] + [f"{name} ({unit_str})" for name, unit_str, _, _ in params] + ["Any Exceedance", "Logged By"]
        for c, h in enumerate(header, 1):
            ws.cell(row=1, column=c, value=h)
        _style_header(ws, 1, len(header))

        # Slow drift per parameter across the whole span (catalyst aging
        # direction is randomised per unit so units diverge realistically).
        drift_rate = {name: rng.normal(0, 0.15) for name, *_ in params}

        exceed_count = 0
        for r, d in enumerate(dates, start=2):
            t = (d - start).days / max(n_days - 1, 1)
            row_exceeded = False
            ws.cell(row=r, column=1, value=d.isoformat())
            ws.cell(row=r, column=2, value=d.strftime("%A"))
            col = 3
            for name, unit_str, target, tolerance in params:
                seasonal = 0.3 * tolerance * np.sin(2 * np.pi * (d.timetuple().tm_yday / 365.0))
                drift = drift_rate[name] * tolerance * t * 4
                noise = rng.normal(0, tolerance * 0.35)
                # Rare excursion spikes -- roughly 1 in 400 readings.
                spike = tolerance * 3 * (rng.random() < 1 / 400)
                value = round(float(target + seasonal + drift + noise + spike), 3)
                cell = ws.cell(row=r, column=col, value=value)
                exceeded = abs(value - target) > tolerance * 1.5
                if exceeded:
                    cell.fill = _EXCEED_FILL
                    row_exceeded = True
                col += 1
            ws.cell(row=r, column=col, value="YES" if row_exceeded else "")
            ws.cell(row=r, column=col + 1, value=vocab.PERSONNEL[r % len(vocab.PERSONNEL)][0])
            if row_exceeded:
                exceed_count += 1

        _autosize(ws, len(header))
        stats[unit] = {"rows": n_days, "exceedances": exceed_count}

    output_path.parent.mkdir(parents=True, exist_ok=True)
    wb.save(str(output_path))
    return stats


def generate_sap_material_master(output_path: Path, n_items: int = 4000) -> dict:
    """A material master export with thousands of line items.

    Not random strings: material descriptions are assembled from
    controlled vocabulary (category + equipment + spec), so a search for
    "hydrocracker catalyst" or "TK-K-01 gasket" returns something
    coherent rather than noise that happens to contain those words.
    """
    rng = np.random.default_rng(42)
    categories = [
        ("Catalyst", ["Ni-Mo", "Co-Mo", "Pt-Re", "Zeolite-Y"], "KG"),
        ("Spare Part", ["Gasket", "Bearing", "Seal Kit", "Valve Trim", "Flange"], "EA"),
        ("Chemical", ["Corrosion Inhibitor", "Antifoam", "Demulsifier", "Biocide"], "LTR"),
        ("Instrument", ["Pressure Transmitter", "Flow Meter", "Temperature Element", "Level Gauge"], "EA"),
        ("Consumable", ["Filter Element", "PPE Kit", "Lubricant", "Welding Rod"], "EA"),
    ]
    plants = ["MRPL-CDU", "MRPL-HCU", "MRPL-CCR", "MRPL-PSA", "MRPL-MSEZ"]

    wb = Workbook()
    ws = wb.active
    ws.title = "Material Master"
    header = [
        "Material No", "Description", "Material Group", "Plant Code",
        "Base Unit", "Vendor", "Unit Price (INR)", "Stock Qty",
        "Reorder Point", "Last Movement Date", "Equipment Ref",
    ]
    for c, h in enumerate(header, 1):
        ws.cell(row=1, column=c, value=h)
    _style_header(ws, 1, len(header))

    vendors = [f"VN-{i:04d}" for i in range(1, 61)]
    start = date(2020, 1, 1)

    for i in range(n_items):
        cat, subtypes, unit_of_measure = categories[i % len(categories)]
        subtype = subtypes[rng.integers(0, len(subtypes))]
        equip = vocab.EQUIPMENT[i % len(vocab.EQUIPMENT)]
        material_no = f"MAT-{100000 + i}"
        desc = f"{subtype} - {cat} for {equip}"
        price = round(float(rng.uniform(150, 85000)), 2)
        stock = int(rng.integers(0, 500))
        reorder = int(rng.integers(5, 60))
        offset_days = int(rng.integers(0, (date(2026, 9, 14) - start).days))
        last_move = (start + timedelta(days=offset_days)).isoformat()

        row = [
            material_no, desc, cat, plants[i % len(plants)], unit_of_measure,
            vendors[i % len(vendors)], price, stock, reorder, last_move, equip,
        ]
        for c, v in enumerate(row, 1):
            ws.cell(row=i + 2, column=c, value=v)

    _autosize(ws, len(header))
    output_path.parent.mkdir(parents=True, exist_ok=True)
    wb.save(str(output_path))
    return {"rows": n_items}


def generate_maintenance_work_orders(output_path: Path, n_orders: int = 3500) -> dict:
    """Work-order history across the archive span, one row per order."""
    rng = np.random.default_rng(7)
    order_types = ["Preventive", "Corrective", "Emergency", "Inspection-Driven", "Turnaround"]
    statuses = ["Closed", "Closed", "Closed", "Closed", "In Progress", "Cancelled"]
    start = date(2020, 1, 1)
    span_days = (date(2026, 9, 14) - start).days

    wb = Workbook()
    ws = wb.active
    ws.title = "Work Orders"
    header = [
        "WO Number", "Unit", "Equipment", "Type", "Status",
        "Created Date", "Closed Date", "Downtime (hrs)", "Assigned To", "Description",
    ]
    for c, h in enumerate(header, 1):
        ws.cell(row=1, column=c, value=h)
    _style_header(ws, 1, len(header))

    for i in range(n_orders):
        unit = vocab.UNITS[i % len(vocab.UNITS)]
        equip = vocab.EQUIPMENT[(i * 3) % len(vocab.EQUIPMENT)]
        wo_type = order_types[i % len(order_types)]
        status = statuses[rng.integers(0, len(statuses))]
        created_offset = int(rng.integers(0, span_days))
        created = start + timedelta(days=created_offset)
        duration = int(rng.integers(1, 21)) if status != "Cancelled" else 0
        closed = created + timedelta(days=duration) if status == "Closed" else None
        downtime = round(float(rng.uniform(0.5, 96)), 1) if wo_type in ("Emergency", "Corrective") else round(float(rng.uniform(0, 8)), 1)
        person = vocab.PERSONNEL[i % len(vocab.PERSONNEL)][0]
        desc = f"{wo_type} maintenance on {equip} ({unit})"

        row = [
            f"WO-{2020 + created.year - 2020:04d}-{i:05d}", unit, equip, wo_type, status,
            created.isoformat(), closed.isoformat() if closed else "",
            downtime, person, desc,
        ]
        for c, v in enumerate(row, 1):
            ws.cell(row=i + 2, column=c, value=v)

    _autosize(ws, len(header))
    output_path.parent.mkdir(parents=True, exist_ok=True)
    wb.save(str(output_path))
    return {"rows": n_orders}
