"""Export every image the pipeline has touched, with everything known
about it, as a self-contained JSON.

"Everything known" means, per image: the pixels themselves (base64, so
the viewer needs no file access), which corpus it came from, and each
distinct kind of understanding the system has produced for it —

  * OCR text (CARD 05 / PaddleOCR) for scans and diagrams, which is the
    text that actually entered the retrieval corpus for that image;
  * the vision model's chart description (CARD 13), which is an
    ESTIMATE and is labelled as one everywhere it appears;
  * ground truth, where the image was generated by us and we therefore
    know the real values — this is what makes the CARD 13 output
    scoreable rather than merely plausible.

Images are inlined as data URIs rather than referenced by path because
the consumer is a published artifact page: it has no access to the
local filesystem, and its CSP blocks loading images from anywhere
except the page itself. A few hundred KB of base64 is the cost of the
page being genuinely self-contained.
"""

import base64
import json
import mimetypes
import sys
from pathlib import Path

CORPUS_IMAGE_DIRS = [
    ("MRPL_RAG_Test_Corpus", "corpus"),
    ("MRPL_Chart_Stress_Corpus", "stress"),
]
_IMAGE_SUFFIXES = {".png", ".jpg", ".jpeg", ".webp"}


def _data_uri(path: Path) -> str:
    mime = mimetypes.guess_type(path.name)[0] or "image/png"
    return f"data:{mime};base64,{base64.b64encode(path.read_bytes()).decode('ascii')}"


def _ocr_text_for(name: str, chunks: list[dict]) -> str | None:
    """The text this image contributed to the retrieval corpus.

    Images enter the corpus through OCR, so their chunks are the OCR
    output — pulled from the already-exported chunk data rather than
    re-running PaddleOCR, which would be several seconds per image for
    a result that must match what was actually indexed anyway.
    """
    texts = [c["text"] for c in chunks if c["source_document"] == name]
    return "\n\n".join(texts) if texts else None


def build(inspection_path: str, chart_results_path: str) -> dict:
    chunks = json.load(open(inspection_path, encoding="utf-8"))["chunks"]

    chart_by_file: dict[str, dict] = {}
    try:
        for r in json.load(open(chart_results_path, encoding="utf-8"))["results"]:
            chart_by_file[r["filename"]] = r
    except (OSError, KeyError, json.JSONDecodeError):
        pass  # chart sweep may not have run yet; images still export fine

    truth_by_file: dict[str, dict] = {}
    gt_path = Path("MRPL_Chart_Stress_Corpus/ground_truth.json")
    if gt_path.exists():
        for g in json.loads(gt_path.read_text(encoding="utf-8")):
            truth_by_file[g["filename"]] = g
    # The unlabeled twin shares the labeled one's real values.
    for name, g in list(truth_by_file.items()):
        if g["has_printed_labels"]:
            twin = name.replace("_labeled.png", "_unlabeled.png")
            if twin in truth_by_file:
                truth_by_file[twin] = {**truth_by_file[twin],
                                       "true_values": g["printed_values"]}
            truth_by_file[name] = {**g, "true_values": g["printed_values"]}

    images = []
    for root, kind in CORPUS_IMAGE_DIRS:
        base = Path(root)
        if not base.exists():
            continue
        for path in sorted(base.rglob("*")):
            if path.suffix.lower() not in _IMAGE_SUFFIXES:
                continue
            name = path.name
            chart = chart_by_file.get(name)
            truth = truth_by_file.get(name)
            images.append({
                "filename": name,
                "corpus": kind,
                "relative_path": str(path).replace("\\", "/"),
                "size_kb": round(path.stat().st_size / 1024, 1),
                "data_uri": _data_uri(path),
                "ocr_text": _ocr_text_for(name, chunks),
                # CARD 13 output. is_estimate is always True by design —
                # carried through so the viewer can never present this
                # with the confidence of a verified number.
                "vision_description": chart.get("description") if chart else None,
                "vision_is_estimate": True if chart else None,
                "vision_seconds": chart.get("seconds") if chart else None,
                "vision_error": chart.get("error") if chart else None,
                "scored": {
                    "type_identified": chart.get("type_identified"),
                    "title_identified": chart.get("title_identified"),
                    "categories_found": chart.get("categories_found"),
                    "categories_total": chart.get("categories_total"),
                    "value_recall": chart.get("value_recall"),
                    "fabricated_value_count": chart.get("fabricated_value_count"),
                } if chart and not chart.get("error") else None,
                "ground_truth": {
                    "chart_type": truth.get("chart_type"),
                    "title": truth.get("title"),
                    "has_printed_labels": truth.get("has_printed_labels"),
                    "true_values": truth.get("true_values"),
                } if truth else None,
            })
    return {"images": images}


if __name__ == "__main__":
    inspection = sys.argv[1] if len(sys.argv) > 1 else "backend/evaluation/inspection_data.json"
    charts = sys.argv[2] if len(sys.argv) > 2 else "backend/evaluation/chart_stress_results.json"
    out = sys.argv[3] if len(sys.argv) > 3 else "backend/evaluation/image_data.json"

    data = build(inspection, charts)
    Path(out).write_text(json.dumps(data), encoding="utf-8")
    total_kb = sum(i["size_kb"] for i in data["images"])
    with_ocr = sum(1 for i in data["images"] if i["ocr_text"])
    with_vision = sum(1 for i in data["images"] if i["vision_description"])
    print(f"Wrote {out}")
    print(f"  images:          {len(data['images'])} ({total_kb:.0f} KB of pixels)")
    print(f"  with OCR text:   {with_ocr}")
    print(f"  with CARD 13:    {with_vision}")
    print(f"  with truth:      {sum(1 for i in data['images'] if i['ground_truth'])}")
